"""Writes crates/skate-game/src/skate3_career/unlock_rules.rs from unlocks.md B.4/B.5's table (work/unlocks/s12_unlock_map.json).

Usage: py -3 -I tools/skate3_unlock_rules.py IN OUT

Each `s1:` / `s2:` / `s2mq:` tag gets one rule, and rulings.md U1/U2 add the `s3:` keys retail never grants offline:
- Start: owned from a new career (the Reset / `start` rule, Skate 2 First Gear / Throwback on the disc).
- Rewards: any of these progression_rewards names was granted.
- Dlc: that DLC id's parts are installed.
- Character: that retail CHARACTERS key is available (roster outfits follow their character).
- Hidden: never shown, Unlock Everything included (U1's developer test items).
"""
import json
import sys

HEADER = "// Generated by tools/skate3_unlock_rules.py from unlocks.md B.5's table; do not edit.\n"

# rulings.md U1: retail's developer test items, hidden everywhere.
HIDDEN = ["s3:cac_dlc_unlock_test", "s3:cac_pack_dwgh_dlc_test"]
# rulings.md U2: every other real item retail never grants offline rides on a reward retail already grants.
OVERRIDES = {
    "s2mq:dr_pepper": ["bs_group_22"],
    "s3:cac_promo_drpepper1": ["bs_group_22"],
    "s3:cac_promo_ps3_invite": ["bs_group_22"],
    "s3:cac_shoe_etnies_inventory": ["path_gvr"],
    "s3:cac_dlc_first_gear_pack_inventory": "start",
    "s3:cac_hom_points": ["steak_man"],
}
# Skate 2's own DLC packs are on the Skate 2 disc (unlocks.md B.3, decision 6).
ON_THE_DISC = {"skate2_first_gear", "skate2_throwback"}


def rule(value):
    if isinstance(value, list):
        return "Rule::Rewards(&[%s])" % ", ".join(json.dumps(v) for v in value)
    if value == "start":
        return "Rule::Start"
    if value.startswith("dlc:"):
        pack = value[4:]
        return "Rule::Start" if pack in ON_THE_DISC else "Rule::Dlc(%s)" % json.dumps(pack)
    if value.startswith("char:"):
        return "Rule::Character(%s)" % json.dumps(value[5:])
    if value == "hidden":
        return "Rule::Hidden"
    raise ValueError("no rule for %r" % value)


def rules(table):
    out = {tag: entry["rule"] for tag, entry in table["tags"].items()}
    out.update(OVERRIDES)
    out.update({tag: "hidden" for tag in HIDDEN})
    return {tag: rule(value) for tag, value in sorted(out.items())}


def source(table):
    lines = [HEADER, "use super::unlocks::Rule;\n", "\n", "/// Every Skate 1 / Skate 2 tag, and the Skate 3 keys rulings.md U1/U2 give a path, sorted by tag.\n"]
    lines.append("pub const RULES: &[(&str, Rule)] = &[\n")
    lines += ["    (%s, %s),\n" % (json.dumps(tag), r) for tag, r in rules(table).items()]
    lines.append("];\n\n/// Items reachable only through Unlock Everything: none (rulings.md U2).\n")
    lines.append("pub const EVERYTHING_ONLY: &[&str] = &[];\n")
    return "".join(lines)


def main(argv):
    src, out = argv[1], argv[2]
    with open(src, encoding="utf-8") as f:
        table = json.load(f)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(source(table))


if __name__ == "__main__":
    main(sys.argv)
